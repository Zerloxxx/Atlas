import Foundation

/// Вариант ответа в опросе.
/// Идентифицируется текстом, а не случайным UUID: список вариантов пересобирается
/// при каждой перерисовке экрана, и со случайным id уже отмеченные ответы
/// переставали совпадать с новыми объектами — галочки слетали.
struct QuestionOption: Identifiable, Hashable {
    var id: String { title }
    let title: String
}
